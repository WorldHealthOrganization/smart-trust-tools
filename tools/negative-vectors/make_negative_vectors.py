#!/usr/bin/env python3
"""Write vectors/negative/negative-vectors.json from the smart-trust PR 129 vector.

Every case is derived from the published certificates (or is a bare string),
so nothing new is signed: a byte changed, a prefix changed, a clock moved, a
trust list emptied. Each case names the step and reason a conforming
verifier must stop at (STT-VER-008), in one language-neutral file that the
Kotlin suite, the Node smoke test and the Rust suite all load (STT-TST-005,
STT-TST-004).

Usage:
    python3 tools/negative-vectors/make_negative_vectors.py           write the file
    python3 tools/negative-vectors/make_negative_vectors.py --check   CI: fail if it is stale
"""

import json
import pathlib
import sys
import zlib

import base45
import cbor2

ROOT = pathlib.Path(__file__).resolve().parents[2]
PR129 = "vectors/smart-trust-pr129/dvc-qr-example-XXA.json"
DSC = "vectors/smart-trust-pr129/dvc-qr-example-XXA-dsc.pem"
OUT = ROOT / "vectors" / "negative" / "negative-vectors.json"
NOW = 1792454400  # 2026-10-20T00:00:00Z, inside the PR 129 certificates' validity


def cose_of(hc1):
    return zlib.decompress(base45.b45decode(hc1[4:]))


def hc1_of(cose):
    return "HC1:" + base45.b45encode(zlib.compress(cose, 9)).decode()


def main():
    certs = json.loads((ROOT / PR129).read_text())["certificates"]
    hepb1, bcg = certs["hepb1"]["hc1"], certs["bcg"]["hc1"]

    tampered_sig = bytearray(cose_of(bcg))
    tampered_sig[-1] ^= 1

    tag = cbor2.loads(cose_of(bcg))
    items = list(tag.value)
    payload = bytearray(items[2])
    payload[-1] ^= 1
    items[2] = bytes(payload)
    tampered_payload = cbor2.dumps(cbor2.CBORTag(18, items))

    claims = cbor2.loads(tag.value[2])
    iat, exp = claims[6], claims[4]

    unsupported_alg = cbor2.dumps([cbor2.dumps({1: -8}), {}, b"", b""])
    too_deep = bytes([0x81] * 40 + [0x00])

    cases = [
        ("prefix-missing", "no context identifier", {"hc1": "NCFOXN"}, "PREFIX", "BAD_PREFIX"),
        ("prefix-version", "a context version other than 1", {"hc1": "HC2:NCFOXN"}, "PREFIX", "UNSUPPORTED_CONTEXT_VERSION"),
        ("base45-lower-case", "Base45 is upper case only", {"hc1": "HC1:abc"}, "BASE45", "BASE45_INVALID"),
        ("base45-dangling", "a single trailing character", {"hc1": "HC1:A"}, "BASE45", "BASE45_INVALID"),
        ("base45-out-of-range", "a triple above 65535", {"hc1": "HC1::::"}, "BASE45", "BASE45_INVALID"),
        ("input-too-long", "longer than any QR code holds", {"hc1": "HC1:" + "0" * 9000}, "PREFIX", "LIMIT_EXCEEDED"),
        ("not-zlib", "Base45 that is not a ZLIB stream", {"hc1": "HC1:" + base45.b45encode(bytes([1, 2, 3])).decode()}, "INFLATE", "INFLATE_FAILED"),
        ("inflate-bomb", "one megabyte of zeros, deflated", {"hc1": hc1_of(bytes(1_000_000))}, "INFLATE", "LIMIT_EXCEEDED"),
        ("cbor-too-deep", "arrays nested beyond the depth limit", {"coseHex": too_deep.hex()}, "COSE", "LIMIT_EXCEEDED"),
        ("unsupported-alg", "alg -8 (EdDSA) in the protected header", {"coseHex": unsupported_alg.hex()}, "HEADER", "UNSUPPORTED_ALGORITHM"),
        ("signature-tampered", "the last signature byte changed", {"hc1": hc1_of(bytes(tampered_sig))}, "SIGNATURE", "SIGNATURE_INVALID"),
        ("payload-tampered", "the last payload byte changed", {"hc1": hc1_of(tampered_payload)}, "SIGNATURE", "SIGNATURE_INVALID"),
        ("unknown-kid", "an empty trust list", {"hc1": hepb1, "trust": []}, "TRUST_LOOKUP", "KID_NOT_FOUND"),
        ("expired", "after exp plus the 300 s skew", {"hc1": bcg, "now": exp + 301}, "TIME", "EXPIRED"),
        ("not-yet-valid", "before iat less the 300 s skew", {"hc1": bcg, "now": iat - 301}, "TIME", "NOT_YET_VALID"),
    ]
    doc = {
        "$comment": "GENERATED by tools/negative-vectors/make_negative_vectors.py from " + PR129 + ". Each case fails at expect.step with expect.reason; inputs are hc1 (a string) or coseHex (raw COSE bytes, verified without the QR layers).",
        "defaults": {"trust": [DSC], "now": NOW, "clockSkewSeconds": 300},
        "cases": [dict(id=i, description=d, **inp, expect={"step": st, "reason": rs}) for i, d, inp, st, rs in cases],
    }
    text = json.dumps(doc, indent=2) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("stale: %s (run tools/negative-vectors/make_negative_vectors.py)" % OUT.relative_to(ROOT), file=sys.stderr)
            return 1
        print("negative vectors are up to date")
        return 0
    OUT.write_text(text)
    print("wrote %d cases to %s" % (len(cases), OUT.relative_to(ROOT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
