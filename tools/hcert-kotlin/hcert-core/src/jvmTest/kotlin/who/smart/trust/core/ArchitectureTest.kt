package who.smart.trust.core

import java.io.File
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import who.smart.trust.payloads.Payload

/**
 * Skill `hcert-library-architecture`: the rules every implementation follows,
 * checked against this one's sources and behaviour.
 */
class ArchitectureTest {
    private val kotlinDir = File(repoRoot, "tools/hcert-kotlin")
    private val mainSources = listOf("commonMain", "jvmMain", "jsMain")
        .flatMap { File(kotlinDir, "hcert-core/src/$it").walkTopDown().filter { f -> f.isFile }.toList() }
    private fun offending(vararg needles: String) =
        mainSources.flatMap { f -> f.readLines().withIndex().filter { (_, l) -> needles.any { it in l } }.map { (i, l) -> "${f.name}:${i + 1}: ${l.trim()}" } }

    @Test fun `STT-GEN-012 STT-VHL-010 STT-VER-009 the core does no network, file or asynchronous I-O`() {
        val found = offending("java.net", "java.nio.file", "java.io.File", "node:fs", "node:http", "node:net", "fetch(", "suspend fun", "kotlinx.coroutines", "System.getenv")
        assertEquals(emptyList(), found)
    }

    @Test fun `STT-SEC-001 the core writes nothing to a log or console`() {
        assertEquals(emptyList(), offending("println(", "print(", "console.", "Logger", "System.err", "System.out"))
    }

    @Test fun `STT-SEC-002 STT-GEN-004 cryptography comes from the platform, with no third-party runtime dependency`() {
        val build = File(kotlinDir, "hcert-core/build.gradle.kts").readText()
        val main = Regex("""commonMain\.dependencies \{(.*?)\}""", RegexOption.DOT_MATCHES_ALL).find(build)!!.groupValues[1]
        assertEquals(listOf("""api(project(":hcert-api"))"""), main.lines().map { it.trim() }.filter { it.isNotEmpty() })
        val jsModules = mainSources.flatMap { Regex("""@file:JsModule\("([^"]+)"\)|@JsModule\("([^"]+)"\)""").findAll(it.readText()).map { m -> m.groupValues.drop(1).first { g -> g.isNotEmpty() } }.toList() }.toSet()
        assertTrue(jsModules.all { it in setOf("node:crypto", "node:zlib", "node:buffer") }, jsModules.toString())
    }

    @Test fun `STT-ISS-003 no private key, and no test key, is in the library's sources`() {
        assertEquals(emptyList(), offending("PRIVATE KEY", "vectors/testkit"))
    }

    @Test fun `STT-GEN-014 STT-GEN-010 the API is generated from the contract and names no WIT`() {
        val api = File(kotlinDir, "hcert-api/src/commonMain").walkTopDown().filter { it.isFile }.toList()
        assertTrue(api.isNotEmpty())
        for (f in api) {
            val text = f.readText()
            assertTrue(text.startsWith("// GENERATED by tools/wit2kotlin/wit2kotlin.py"), f.name)
            val body = text.substringAfter("\n")
            assertTrue("WIT" !in body && "World" !in body && "WitResult" !in body, "${f.name} names the contract language")
        }
    }

    @Test fun `STT-GEN-002 every step is callable on its own, and the steps compose to the pipeline`() {
        val issued = Testkit.issue(Payload.DvcMin(NEWBORN))
        val zlib = HcertCodec.zlibCompress(issued.cose, 9)
        val text = "HC1:" + HcertCodec.base45Encode(zlib)
        assertEquals(issued.hc1, text)
        val back = HcertCodec.zlibInflate(HcertCodec.base45Decode(HcertCodec.detectContext(text).ok().second).ok(), 65536).ok()
        assertContentEquals(issued.cose, back)
        val s = HcertCose.parseSign1(back, DEFAULT_LIMITS).ok()
        HcertCose.verifySign1(s, Testkit.esDer).ok()
        assertContentEquals(s.payload, HcertCodec.cborDeterministic(s.payload, DEFAULT_LIMITS).ok())
    }
}
